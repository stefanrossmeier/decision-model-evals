def make_cases() -> list[dict]:
    cases: list[dict] = []
    for domain, spec in DOMAINS.items():
        assert len(spec.archetypes) == 10, (domain, len(spec.archetypes))
        seq = 0
        for archetype_idx, archetype in enumerate(spec.archetypes):
            for context_idx, (context, delta, tags) in enumerate(CONTEXTS):
                seq += 1
                score = max(0, min(len(spec.score_criteria) - 1, archetype.score + delta))
                state = {
                    "record_id": f"{domain[:4].upper()}-{seq:04d}",
                    "summary": archetype.text,
                    "operational_context": context,
                }
                base_meta = {
                    "corpus_version": "v1",
                    "authorship": "rule-authored synthetic scenario",
                    "archetype": archetype_idx,
                    "context_variant": context_idx,
                }
                base_tags = ["real_world_style", domain, *tags]
                if domain == "agent_security":
                    base_tags.extend(["owasp_inspired", "untrusted_content"])
                if domain == "workflow_routing":
                    base_tags.extend(["workflow_routing", "agent_orchestration"])
                stem = f"dmv1-{domain}-{seq:04d}"
                cases.append(
                    {
                        "id": stem + "-choice",
                        "primitive": "choice",
                        "domain": domain,
                        "task": spec.choice_task,
                        "state": state,
                        "instructions": spec.choice_instructions,
                        "criteria": spec.choice_criteria,
                        "gold": {"choice": archetype.choice, "rationale": archetype.rationale},
                        "tags": base_tags,
                        "metadata": base_meta,
                    }
                )
                cases.append(
                    {
                        "id": stem + "-noul",
                        "primitive": "noul",
                        "domain": domain,
                        "task": spec.noul_task,
                        "state": state,
                        "instructions": spec.noul_instructions,
                        "criteria": spec.noul_criteria,
                        "gold": {"noul": archetype.noul, "rationale": archetype.rationale},
                        "tags": base_tags,
                        "metadata": base_meta,
                    }
                )
                cases.append(
                    {
                        "id": stem + "-score",
                        "primitive": "score",
                        "domain": domain,
                        "task": spec.score_task,
                        "state": state,
                        "instructions": spec.score_instructions,
                        "criteria": spec.score_criteria,
                        "gold": {
                            "score": score,
                            "rationale": f"{archetype.rationale} Context adjustment {delta:+d} on the domain rubric.",
                        },
                        "tags": base_tags,
                        "metadata": base_meta,
                    }
                )
    return cases


def stable_rank(case_id: str, salt: str) -> str:
    return hashlib.sha256(f"{SEED}:{salt}:{case_id}".encode()).hexdigest()


def stratified(cases: list[dict], total: int, salt: str) -> list[str]:
    domains = sorted(DOMAINS)
    primitives = ["choice", "noul", "score"]
    buckets: dict[tuple[str, str], list[dict]] = {}
    for domain in domains:
        for primitive in primitives:
            items = [c for c in cases if c["domain"] == domain and c["primitive"] == primitive]
            buckets[(domain, primitive)] = sorted(items, key=lambda c: stable_rank(c["id"], salt))

    keys = [(d, p) for d in domains for p in primitives]
    quota, remainder = divmod(total, len(keys))
    selected: list[str] = []
    for idx, key in enumerate(keys):
        n = quota + (1 if idx < remainder else 0)
        selected.extend(c["id"] for c in buckets[key][:n])
    return sorted(selected, key=lambda x: stable_rank(x, salt + ":order"))


def write_suite(name: str, case_ids: list[str], description: str) -> None:
    payload = {
        "name": name,
        "description": description,
        "corpus_version": "v1",
        "case_ids": case_ids,
    }
    (SUITES / f"{name}.yaml").write_text(yaml.safe_dump(payload, sort_keys=False, width=120), encoding="utf-8")


def main() -> None:
    cases = make_cases()
    expected = len(DOMAINS) * 10 * len(CONTEXTS) * 3
    assert len(cases) == expected == 5760, (len(cases), expected)
    CORPUS.parent.mkdir(parents=True, exist_ok=True)
    SUITES.mkdir(parents=True, exist_ok=True)
    with CORPUS.open("w", encoding="utf-8") as handle:
        for case in cases:
            handle.write(json.dumps(case, ensure_ascii=False, sort_keys=True) + "\n")

    all_ids = [c["id"] for c in cases]
    write_suite("full", all_ids, "All 5,760 authored cases. Primary quality benchmark.")
    write_suite("core", stratified(cases, 1500, "core"), "1,500-case stratified primary development benchmark.")
    write_suite("quick", stratified(cases, 300, "quick"), "300-case stratified iteration benchmark.")
    write_suite("perf", stratified(cases, 180, "perf"), "180-case stratified timing/cost workload.")

    smoke_domains = ["workflow_routing", "agent_security", "customer_support", "it_operations", "research", "compliance"]
    smoke_ids: list[str] = []
    for idx, domain in enumerate(smoke_domains):
        for primitive_idx, primitive in enumerate(("choice", "noul", "score")):
            items = [c for c in cases if c["domain"] == domain and c["primitive"] == primitive]
            items.sort(key=lambda c: stable_rank(c["id"], f"smoke:{idx}:{primitive_idx}"))
            smoke_ids.append(items[0]["id"])
    write_suite("smoke", smoke_ids, "18-case cheap end-to-end smoke suite: six cases per primitive across six domains.")

    probe_ids = []
    for domain, primitive in [("workflow_routing", "choice"), ("agent_security", "noul"), ("customer_support", "score")]:
        items = [c for c in cases if c["domain"] == domain and c["primitive"] == primitive]
        items.sort(key=lambda c: stable_rank(c["id"], "probe"))
        probe_ids.append(items[0]["id"])
    write_suite("probe", probe_ids, "Three requests, one per primitive. Cheapest setup/API verification.")

    for domain, name, description in [
        ("workflow_routing", "routing", "All workflow-routing cases (360)."),
        ("agent_security", "agent-security", "All OWASP-inspired model/agent-influencing cases (360)."),
    ]:
        ids = [c["id"] for c in cases if c["domain"] == domain]
        write_suite(name, ids, description)

    rng = random.Random(SEED)
    ids = all_ids.copy()
    rng.shuffle(ids)
    assert len(ids) == len(set(ids))
    print(f"wrote {len(cases)} cases across {len(DOMAINS)} domains")


if __name__ == "__main__":
    main()
